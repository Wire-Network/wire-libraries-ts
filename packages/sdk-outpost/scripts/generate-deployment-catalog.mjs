import {
  GeneratedCatalogFile,
  readCurrentDeploymentId,
  readDeploymentDocuments,
  writeTypescript
} from "./deployment-utils.mjs"

const documents = await readDeploymentDocuments(),
  currentId = await readCurrentDeploymentId(),
  ids = new Set(),
  wireChainIds = new Set()

for (const document of documents) {
  if (ids.has(document.id)) {
    throw new Error(`Duplicate outpost deployment id ${document.id}`)
  }
  if (wireChainIds.has(document.wire.chainId)) {
    throw new Error(
      `Duplicate outpost deployment Wire chain ${document.wire.chainId}`
    )
  }
  ids.add(document.id)
  wireChainIds.add(document.wire.chainId)
}

if (!ids.has(currentId)) {
  throw new Error(
    `Current outpost deployment ${currentId} is not in the catalog`
  )
}

await writeTypescript(
  GeneratedCatalogFile,
  `
    /* Autogenerated file. Do not edit manually. */

    /** Untrusted deployment documents validated by Registry at module load. */
    export const OutpostDeploymentDocuments: readonly unknown[] = ${JSON.stringify(documents, null, 2)}

    /** Deployment whose ABI and IDL surfaces own the generated client types. */
    export const CurrentOutpostDeploymentId = ${JSON.stringify(currentId)}
  `
)
