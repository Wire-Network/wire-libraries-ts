import Fs from "node:fs/promises"
import Path from "node:path"
import { fileURLToPath } from "node:url"

import { convertIdlToCamelCase } from "@coral-xyz/anchor/dist/cjs/idl.js"
import { format } from "prettier"

const packagePath = Path.resolve(
    Path.dirname(fileURLToPath(import.meta.url)),
    ".."
  ),
  idlFile = Path.join(packagePath, "src/assets/solana/sim2/liqsol_core.json"),
  outputFile = Path.join(
    packagePath,
    "src/programs/solana/generated/LiqsolCore.ts"
  ),
  rawIdl = JSON.parse(await Fs.readFile(idlFile, "utf8")),
  idl = convertIdlToCamelCase(rawIdl),
  source = `
    /* Autogenerated file. Do not edit manually. */
    /* eslint-disable */
    import type { Idl } from "@coral-xyz/anchor"

    const liqsolCoreIdlValue = ${JSON.stringify(idl, null, 2)} as const

    /** Strict Anchor IDL type generated from the checked-in liqsol_core artifact. */
    export type LiqsolCore = Idl & typeof liqsolCoreIdlValue

    /** Camel-cased liqsol_core IDL consumed by Anchor's typed Program client. */
    export const liqsolCoreIdl = liqsolCoreIdlValue as LiqsolCore
  `,
  formattedSource = await format(source, {
    parser: "typescript",
    semi: false,
    singleQuote: false,
    trailingComma: "none"
  })

await Fs.writeFile(outputFile, formattedSource)
