// noinspection JSUnresolvedReference

/**
 * pnpm hook to resolve @wireio packages from the local wire-libraries-ts monorepo.
 *
 * Usage:
 *   1. Build the required sibling-repository artifact outputs.
 *   2. Set the corresponding WIRE_LINK_LOCAL_* environment variable.
 *   3. Run `pnpm install --lockfile=false` to use local paths instead of the registry.
 *
 * Docs: https://pnpm.io/pnpmfile
 */

const Path = require("path")
const Fs = require("node:fs")

const linkLocalOppModelsEnv = "WIRE_LINK_LOCAL_OPP_MODELS"
const linkLocalOutpostArtifactsEnv = "WIRE_LINK_LOCAL_OUTPOST_ARTIFACTS"
const localOppModelTargets = ["typescript", "solidity"]
const localOutpostArtifactPackages = [
  [
    "@wireio/outpost-ethereum-artifacts",
    Path.resolve(__dirname, "..", "wire-ethereum", "sdk-artifacts")
  ],
  [
    "@wireio/outpost-solana-artifacts",
    Path.resolve(__dirname, "..", "wire-solana", "sdk-artifacts")
  ]
]

/**
 * Checks whether a path exists and is a directory, without throwing.
 *
 * @param {string} dirPath
 * @returns {boolean}
 */
function isDirectory(dirPath) {
  try {
    return Fs.lstatSync(dirPath).isDirectory()
  } catch {
    return false
  }
}

/**
 * Checks whether an opt-in local-link environment variable is enabled.
 *
 * @param {string} name
 * @returns {boolean}
 */
function isEnabledEnvironment(name) {
  return process.env[name] === "1" || process.env[name] === "true"
}

/**
 * Map of package names to their local directory in wire-libraries-ts.
 * Uncomment the entries you want to link locally.
 */
const localOverrides = {}

/**
 * Links local OPP model outputs for platform builds that already built wire-sysio.
 * Normal package installs keep registry resolution so pnpm-lock.yaml is portable.
 */
function appendLocalOppModelOverrides() {
  if (!isEnabledEnvironment(linkLocalOppModelsEnv)) {
    return
  }

  localOppModelTargets
    .map(target => [
      `@wireio/opp-${target}-models`,
      Path.resolve(__dirname, "..", "wire-sysio", "build", "opp", target)
    ])
    .filter(([, path]) => isDirectory(path))
    .forEach(([pkgName, path]) => {
      localOverrides[pkgName] = path
    })
}

/**
 * Links source-owned outpost packages generated by sibling chain repositories.
 * Standalone and release installs keep registry resolution so their lockfile
 * remains portable and exact published versions stay authoritative.
 */
function appendLocalOutpostArtifactOverrides() {
  if (!isEnabledEnvironment(linkLocalOutpostArtifactsEnv)) {
    return
  }

  localOutpostArtifactPackages
    .filter(([, path]) => isDirectory(path))
    .forEach(([pkgName, path]) => {
      localOverrides[pkgName] = path
    })
}

appendLocalOppModelOverrides()
appendLocalOutpostArtifactOverrides()

/**
 * `readPackage` hook, which links locally available versions of
 * shared libraries and models.
 *
 * @param pkg
 * @param context
 * @returns {*}
 */
function readPackage(pkg, context) {
  for (const [name, localPath] of Object.entries(localOverrides)) {
    if (pkg.dependencies && pkg.dependencies[name]) {
      pkg.dependencies[name] = `link:${localPath}`
      context.log(`Linked ${name} -> ${localPath}`)
    }
    if (pkg.devDependencies && pkg.devDependencies[name]) {
      pkg.devDependencies[name] = `link:${localPath}`
      context.log(`Linked ${name} -> ${localPath}`)
    }
  }
  return pkg
}

module.exports = {
  hooks: {
    readPackage
  }
}
